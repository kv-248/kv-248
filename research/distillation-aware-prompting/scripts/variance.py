"""E2 -- Where does output variation come from: the seed or the wording?

For each intent, J meaning-preserving paraphrases x S seeds are generated by every variant.
Reports the prompt share of variation rho (metrics.variance_decomposition) and, at equal
image count K = min(J, S), the diversity (Vendi) and success rate of a seed set (original
prompt, K seeds) vs a paraphrase set (K paraphrases, one seed).

  python scripts/variance.py --family sdxl --paraphrases runs/paraphrases.json \
      --embedder facebook/dinov2-base --judge hf:Qwen/Qwen2.5-VL-7B-Instruct --out runs/e2_sdxl
Paraphrases are generated once (--llm) and cached so every variant sees the same wording.
"""

from __future__ import annotations

import argparse
import gc
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from dap import make_judge, make_llm  # noqa: E402
from dap.embed import ImageEmbedder, pixel_embed  # noqa: E402
from dap.generation import CONFIG_PATH, Generator, load_families  # noqa: E402
from dap.judges import score_intent  # noqa: E402
from dap.metrics import variance_decomposition, vendi_score  # noqa: E402
from dap.questions import load_geneval  # noqa: E402
from dap.rewrite import paraphrase  # noqa: E402


def get_paraphrases(intents, path: Path, llm, j: int) -> dict[str, list[str]]:
    cache = json.loads(path.read_text()) if path.exists() else {}
    missing = [it.prompt for it in intents if len(cache.get(it.prompt, [])) < j - 1]
    if missing and llm is None:
        raise SystemExit(f"{len(missing)} prompts lack paraphrases; pass --llm to generate them")
    for p in missing:
        cache[p] = paraphrase(llm, p, n=j - 1)
        path.write_text(json.dumps(cache, indent=1))
    return cache


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--family", required=True)
    ap.add_argument("--variants", nargs="*")
    ap.add_argument("--config", default=str(CONFIG_PATH))
    ap.add_argument("--limit", type=int, default=100)
    ap.add_argument("--tags", nargs="*")
    ap.add_argument("--geneval-meta")
    ap.add_argument("--n-para", type=int, default=6, help="J, including the original prompt")
    ap.add_argument("--n-seeds", type=int, default=6, help="S")
    ap.add_argument("--paraphrases", required=True)
    ap.add_argument("--llm")
    ap.add_argument("--judge", default="mock")
    ap.add_argument("--embedder", default="pixel", help="'pixel' or a HF model id (DINOv2 / CLIP)")
    ap.add_argument("--device", default="cuda")
    ap.add_argument("--dtype", default="bfloat16")
    ap.add_argument("--batch-size", type=int, default=8)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    intents = load_geneval(args.geneval_meta, limit=args.limit, tags=args.tags)
    paras = get_paraphrases(intents, Path(args.paraphrases), make_llm(args.llm), args.n_para)
    judge = make_judge(args.judge, device=args.device)
    embed = pixel_embed if args.embedder == "pixel" else ImageEmbedder(args.embedder, device=args.device)
    variants = load_families(args.config)[args.family]
    if args.variants:
        variants = [v for v in variants if v.role == "teacher" or v.name in args.variants]

    J, S = args.n_para, args.n_seeds
    summary = {}
    for spec in variants:
        gen = Generator(spec, device=args.device, dtype=args.dtype).load()
        embs, succ = [], []
        for intent in intents:
            prompts = ([intent.prompt] + paras[intent.prompt])[:J]
            grid_p = [p for p in prompts for _ in range(S)]
            grid_s = [s for _ in prompts for s in range(S)]
            images = gen.generate_batched(grid_p, grid_s, batch_size=args.batch_size)
            embs.append(np.asarray(embed(images)).reshape(len(prompts), S, -1))
            succ.append(np.array([s["success"] for s in score_intent(judge, images, intent)]).reshape(len(prompts), S))
        E = np.stack(embs)  # [I, J, S, D]
        Y = np.stack(succ)  # [I, J, S]
        dec = variance_decomposition(E)
        K = min(J, S)
        seed_set = [vendi_score(E[i, 0, :K]) for i in range(len(intents))]  # original prompt, K seeds
        para_set = [vendi_score(E[i, :K, 0]) for i in range(len(intents))]  # K paraphrases, seed 0
        summary[spec.name] = {
            "role": spec.role, "steps": spec.steps, **dec,
            "vendi_seed_set": float(np.mean(seed_set)), "vendi_para_set": float(np.mean(para_set)),
            "success_seed_set": float(Y[:, 0, :K].mean()), "success_para_set": float(Y[:, :K, 0].mean()),
        }
        np.save(out / f"emb_{spec.name}.npy", E.astype(np.float16))
        np.save(out / f"succ_{spec.name}.npy", Y)
        del gen
        gc.collect()
        print(spec.name, json.dumps({k: round(v, 4) if isinstance(v, float) else v for k, v in summary[spec.name].items()}))
    (out / "summary.json").write_text(json.dumps(summary, indent=1))


if __name__ == "__main__":
    main()
